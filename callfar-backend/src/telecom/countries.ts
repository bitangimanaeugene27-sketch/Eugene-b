export function getCountryByCode(code: string): CountryInfo | undefined {
  return COUNTRIES_DATABASE.find((c) => c.code.toUpperCase() === code.toUpperCase());
}

export function getCountryByDialCode(dialCode: string): CountryInfo | undefined {
  const clean = dialCode.startsWith('+') ? dialCode : `+${dialCode}`;
  return COUNTRIES_DATABASE.find((c) => c.dialCode === clean);
}
