import { PrismaClient, CallType, CallStatus, ParticipantStatus, ContactRequestStatus, Role, LicenseTier, LicenseStatus } from '@prisma/client';
import bcrypt from 'bcryptjs';

const prisma = new PrismaClient();

async function main() {
  console.log('🌱 Seeding CallFar database with initial test users and admin licenses...');

  // Clean existing data for clean seed
  await prisma.licenseKey.deleteMany();
  await prisma.userLicense.deleteMany();
  await prisma.callParticipant.deleteMany();
  await prisma.call.deleteMany();
  await prisma.message.deleteMany();
  await prisma.conversationMember.deleteMany();
  await prisma.conversation.deleteMany();
  await prisma.contact.deleteMany();
  await prisma.contactRequest.deleteMany();
  await prisma.blockedUser.deleteMany();
  await prisma.refreshToken.deleteMany();
  await prisma.userSettings.deleteMany();
  await prisma.userProfile.deleteMany();
  await prisma.user.deleteMany();

  const passwordHash = await bcrypt.hash('Password123!', 10);

  // 1. Create Alice as System Administrator with MASTER_ADMIN License
  const alice = await prisma.user.create({
    data: {
      email: 'alice@callfar.test',
      username: 'alice',
      passwordHash,
      phoneNumber: '+14155550101',
      isPhoneVerified: true,
      role: Role.ADMIN,
      profile: {
        create: {
          displayName: 'Alice Cooper (Admin)',
          bio: 'CallFar System Administrator with Master License privileges.',
          avatarUrl: 'https://images.unsplash.com/photo-1494790108377-be9c29b29330?w=150',
          isOnline: true,
        },
      },
      settings: {
        create: {
          theme: 'dark',
          allowIncomingCalls: true,
          allowReadReceipts: true,
        },
      },
      license: {
        create: {
          tier: LicenseTier.MASTER_ADMIN,
          status: LicenseStatus.ACTIVE,
          maxCallDurationMinutes: -1, // Unlimited
          canVideoCall: true,
          canHdAudio: true,
          canScreenShare: true,
          canRecordCalls: true,
          priorityTurn: true,
          expiresAt: null, // Lifetime
        },
      },
    },
  });

  // 2. Create Bob as PRO member
  const bob = await prisma.user.create({
    data: {
      email: 'bob@callfar.test',
      username: 'bob',
      passwordHash,
      phoneNumber: '+14155550102',
      isPhoneVerified: true,
      role: Role.MEMBER,
      profile: {
        create: {
          displayName: 'Bob Smith',
          bio: 'Available for video calls.',
          avatarUrl: 'https://images.unsplash.com/photo-1507003211169-0a1dd7228f2d?w=150',
          isOnline: true,
        },
      },
      settings: {
        create: {
          theme: 'dark',
          allowIncomingCalls: true,
          allowReadReceipts: true,
        },
      },
      license: {
        create: {
          tier: LicenseTier.PRO,
          status: LicenseStatus.ACTIVE,
          maxCallDurationMinutes: -1,
          canVideoCall: true,
          canHdAudio: true,
          canScreenShare: true,
          canRecordCalls: false,
          priorityTurn: true,
          expiresAt: new Date(Date.now() + 30 * 24 * 60 * 60 * 1000), // 30 days
        },
      },
    },
  });

  // 3. Create Charlie as standard FREE member
  const charlie = await prisma.user.create({
    data: {
      email: 'charlie@callfar.test',
      username: 'charlie',
      passwordHash,
      phoneNumber: '+14155550103',
      isPhoneVerified: false,
      role: Role.MEMBER,
      profile: {
        create: {
          displayName: 'Charlie Davis',
          bio: 'Building scalable real-time systems.',
          avatarUrl: 'https://images.unsplash.com/photo-1500648767791-00dcc994a43e?w=150',
          isOnline: false,
        },
      },
      settings: {
        create: {
          theme: 'system',
          allowIncomingCalls: true,
        },
      },
      license: {
        create: {
          tier: LicenseTier.FREE,
          status: LicenseStatus.ACTIVE,
          maxCallDurationMinutes: 15,
          canVideoCall: true,
          canHdAudio: false,
          canScreenShare: false,
          canRecordCalls: false,
          priorityTurn: false,
        },
      },
    },
  });

  // Create sample redeemable license keys generated by Alice
  await prisma.licenseKey.createMany({
    data: [
      {
        key: 'CALLFAR-PRO-2026-VIP',
        tier: LicenseTier.PRO,
        durationDays: 30,
        createdById: alice.id,
        notes: 'VIP Community 30-Day Pro Pass',
      },
      {
        key: 'CALLFAR-ENT-LIFETIME-GOLD',
        tier: LicenseTier.ENTERPRISE,
        durationDays: 365,
        createdById: alice.id,
        notes: 'Enterprise 1-Year Pass with Recording & Priority TURN',
      },
    ],
  });

  console.log(`Created users: Alice (${alice.id}), Bob (${bob.id}), Charlie (${charlie.id})`);

  // 4. Create mutual contacts (Alice <-> Bob)
  await prisma.contact.createMany({
    data: [
      { userId: alice.id, contactUserId: bob.id, aliasName: 'Bobby' },
      { userId: bob.id, contactUserId: alice.id, aliasName: 'Alice C.' },
    ],
  });

  // 5. Create a pending request (Charlie -> Alice)
  await prisma.contactRequest.create({
    data: {
      senderId: charlie.id,
      receiverId: alice.id,
      status: ContactRequestStatus.PENDING,
    },
  });

  // 6. Create Direct Conversation between Alice and Bob
  const conversation = await prisma.conversation.create({
    data: {
      type: 'DIRECT',
      members: {
        create: [
          { userId: alice.id, role: 'ADMIN' },
          { userId: bob.id, role: 'MEMBER' },
        ],
      },
    },
  });

  // 7. Seed Initial Messages
  await prisma.message.createMany({
    data: [
      {
        conversationId: conversation.id,
        senderId: alice.id,
        content: 'Hey Bob! Testing internet calls on CallFar.',
        status: 'READ',
        createdAt: new Date(Date.now() - 3600000),
      },
      {
        conversationId: conversation.id,
        senderId: bob.id,
        content: 'Hi Alice! Video and audio quality is pristine.',
        status: 'READ',
        createdAt: new Date(Date.now() - 3500000),
      },
    ],
  });

  // 8. Seed Sample Call Record
  const sampleCall = await prisma.call.create({
    data: {
      initiatorId: alice.id,
      conversationId: conversation.id,
      callType: CallType.VIDEO,
      status: CallStatus.COMPLETED,
      startedAt: new Date(Date.now() - 7200000),
      answeredAt: new Date(Date.now() - 7195000),
      endedAt: new Date(Date.now() - 7000000),
      durationSeconds: 195,
      participants: {
        create: [
          { userId: alice.id, status: ParticipantStatus.CONNECTED },
          { userId: bob.id, status: ParticipantStatus.CONNECTED },
        ],
      },
    },
  });

  console.log('✅ CallFar database successfully seeded!');
  console.log('Login credentials for testing:');
  console.log('  Username: alice  | Password: Password123!');
  console.log('  Username: bob    | Password: Password123!');
  console.log('  Username: charlie| Password: Password123!');
}

main()
  .catch((e) => {
    console.error('Seeding failed:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
